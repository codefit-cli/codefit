package scaffold

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

// yamlScalar renders s as a YAML-safe scalar (correctly quoted/escaped for any
// content — a project name with quotes, backslashes, colons, …). The config name
// is free text (the project dir), so it must never be interpolated raw, or a
// hostile/odd dir name would produce an unloadable config reported as success.
func yamlScalar(s string) string {
	out, err := yaml.Marshal(s)
	if err != nil {
		return `""` // unreachable for strings; stay valid YAML if it ever happens
	}
	return strings.TrimRight(string(out), "\n")
}

var configFuncs = template.FuncMap{"q": yamlScalar}

// configTemplate renders a commented .codefit.yaml from a ProjectInfo. It is a
// commented template (not yaml.Marshal of the Config struct, which would dump
// every zero-value field): the file is committed and human-edited, so it stays
// minimal and readable. Sections not detected (database) are omitted; config
// loading fills the rest with defaults.
//
// Only fields within config's validated enums are ever emitted, so the output
// always round-trips through config.Load.
var configTemplate = template.Must(template.New("config").Funcs(configFuncs).Parse(
	`# .codefit.yaml — project config for codefit, the AI-generated-code auditor.
# Committed and shared, like .eslintrc. Generated by ` + "`codefit init`" + `; edit freely.
version: "1"

project:
  name: {{q .Name}}
{{- if not .Detected}}
  # codefit found no language provider it can audit in this project root.
  # It looks for {{.Markers}}
  # directly under the root, so a monorepo should run ` + "`codefit init`" + ` per
  # sub-project root instead.
  #
  # The value below records THAT — codefit's detection result — and is never a
  # claim about your project: your code has a language, codefit just registers
  # no provider that can audit it. Nothing here scans code; see the note where
  # ` + "`database:`" + ` would be for what still runs.
{{- end}}
  language: {{q .Language}}
{{- if .Framework}}
  framework: {{q .Framework}}
{{- end}}
{{- if .Detected}}
  # path_criticality weights finding severity by location: a secret in a test is
  # noise; in production it is critical. Globs are project-relative.
  path_criticality:
    production:
{{- range .Production}}
      - {{q .}}
{{- end}}
{{- if .Test}}
    test:
{{- range .Test}}
      - {{q .}}
{{- end}}
{{- end}}
{{- if .Example}}
    example:
{{- range .Example}}
      - {{q .}}
{{- end}}
{{- end}}
{{- else}}
  # path_criticality is absent on purpose, not left empty. No language provider
  # resolved, so codefit has no defaults for this project and invents none —
  # globs guessed for a tree codefit never inspected would silently reclassify
  # your files.
  #
  # CONSEQUENCE: no path is classified, so the test-path re-weighting never
  # fires and every finding keeps its natural severity. Nothing is downgraded
  # behind your back; nothing in a test file is quieted either.
  #
  # Add it yourself to get that weighting. Globs are project-relative:
  #
  #   path_criticality:
  #     production:
  #       - "src/**"
  #     test:
  #       - "**/*_test.*"
{{- end}}
{{- if .SchemaPaths}}

database:
{{- if .ORM}}
  # ` + "`orm:`" + ` is recorded for you, not for codefit: no sensor reads it. What turns
  # the DB dimension on is ` + "`schema_paths`" + ` below — that is the field the audit
  # actually consumes, and the only one whose absence makes it audit nothing.
  orm: {{q .ORM}}
{{- end}}
{{- if .DBType}}
  type: {{q .DBType}}
{{- end}}
{{- if .DBParadigm}}
  paradigm: {{q .DBParadigm}}
{{- end}}
  schema_paths:
{{- range .SchemaPaths}}
    - {{q .}}
{{- end}}
{{- else}}

# No ` + "`database:`" + ` section was written, and codefit is telling you rather than
# letting you find out from an empty report: it detects a schema ONLY from a
# Prisma schema.prisma. SQL migration directories — Flyway, golang-migrate,
# plain .sql DDL — are NOT detected yet. A detected ORM name is not a schema
# either: no sensor reads it, so it buys this config nothing on its own.
#
# So AS WRITTEN this config audits no schema. If this project has one, point
# codefit at it by hand and the DB dimension runs on the next scan:
#
#   database:
#     type: "postgresql"   # postgresql | mysql | sqlserver
#     schema_paths:
#       - "db/migrations"
#
# ` + "`type:`" + ` is optional, and leaving it out has a CONSEQUENCE worth knowing:
# codefit then parses your SQL DDL as PostgreSQL and says nothing about having
# chosen. A MySQL or SQL Server schema is silently mis-parsed, and every DB
# finding after it reasons over a schema you do not have. sqlite is the one
# value codefit refuses outright instead of guessing at.
{{- end}}
`))

// configView is the flattened, slash-normalized data the config template needs.
type configView struct {
	Name, Language, Framework string
	// Detected mirrors ProjectInfo.Detected(): whether a real language provider
	// resolved. The template branches on this, never on the sentinel spelling.
	Detected bool
	// Markers is the prose list of the marker files codefit looks for, derived
	// from the registry. The template must never spell a marker name itself.
	Markers                   string
	Production, Test, Example []string
	ORM, DBType, DBParadigm   string
	SchemaPaths               []string
}

// RenderConfig renders a commented .codefit.yaml for the detected project. Paths
// are slash-normalized so the committed file is portable across operating systems.
func RenderConfig(info ProjectInfo) ([]byte, error) {
	view := configView{
		Name:        info.Name,
		Language:    info.Language,
		Detected:    info.Detected(),
		Markers:     markerList(),
		Framework:   info.Framework,
		Production:  toSlashAll(info.PathCriticality.Production),
		Test:        toSlashAll(info.PathCriticality.Test),
		Example:     toSlashAll(info.PathCriticality.Example),
		ORM:         info.ORM,
		DBType:      info.DBType,
		DBParadigm:  info.DBParadigm,
		SchemaPaths: toSlashAll(info.SchemaPaths),
	}
	var buf bytes.Buffer
	if err := configTemplate.Execute(&buf, view); err != nil {
		return nil, fmt.Errorf("rendering config: %w", err)
	}
	return buf.Bytes(), nil
}

func toSlashAll(in []string) []string {
	if len(in) == 0 {
		return nil
	}
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = filepath.ToSlash(s)
	}
	return out
}
